void usage(const char *argv0) {
  std::printf("Usage: %s [--device N] [--warmup W] [--iters I] [--csv PATH] "
              "[--input-init memset|formula|random|random-signed8] "
              "[--validate] [--validate-size N] "
              "[--validate-pattern pattern|ones]\n",
              argv0);
