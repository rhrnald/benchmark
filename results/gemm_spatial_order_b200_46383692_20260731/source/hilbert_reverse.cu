__device__ __forceinline__ uint32_t smem_ptr_u32(const void *ptr) {
  uint32_t addr;
  asm volatile("{ .reg .u64 u64addr; cvta.to.shared.u64 u64addr, %1; "
               "cvt.u32.u64 %0, u64addr; }"
               : "=r"(addr)
               : "l"(ptr));
